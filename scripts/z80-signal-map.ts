/**
 * Writes docs/z80-signal-map.md: the hand-named signals of the gate-level Z80,
 * grouped by name prefix, with how widely each family is spread through the build.
 * Run: npm run gen:z80-map
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ChipLibrary } from '../src/sim/ChipLibrary.js';
import { Circuit } from '../src/sim/Circuit.js';
import { buildZ80Cpu } from '../src/sim/blocks.js';
import { seedStandardCells } from '../src/sim/stdcells.js';

const ADDR_BITS = 12;
const HUB_COUNT = 30;
const AUTO_NAME = /^(_?N\d+|BUS\d+)$/;
const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'z80-signal-map.md');

const library = new ChipLibrary();
seedStandardCells(library);
const circuit = new Circuit();
buildZ80Cpu(circuit, library, ADDR_BITS, undefined, { x: 0, y: 0 });

const components = [...circuit.components.values()];
const kinds = new Map<string, number>();
for (const c of components) kinds.set(c.kind, (kinds.get(c.kind) ?? 0) + 1);

interface Signal {
  refs: number;
  first: number;
  last: number;
}
const signals = new Map<string, Signal>();
components.forEach((c, order) => {
  if (c.kind !== 'label') return;
  const s = signals.get(c.name) ?? { refs: 0, first: order, last: order };
  s.refs++;
  s.last = order;
  signals.set(c.name, s);
});

const named = [...signals.entries()].filter(([name]) => !AUTO_NAME.test(name));
const familyOf = (name: string): string => (name.includes('_') ? name.split('_')[0]! : name.replace(/\d+$/, ''));

interface Family {
  names: string[];
  refs: number;
  first: number;
  last: number;
}
const families = new Map<string, Family>();
for (const [name, s] of named) {
  const f = families.get(familyOf(name)) ?? { names: [], refs: 0, first: s.first, last: s.last };
  f.names.push(name);
  f.refs += s.refs;
  f.first = Math.min(f.first, s.first);
  f.last = Math.max(f.last, s.last);
  families.set(familyOf(name), f);
}

const pct = (order: number): string => `${Math.round((100 * order) / components.length)}%`;
const byName = (a: [string, unknown], b: [string, unknown]): number => a[0].localeCompare(b[0]);
const familyRows = [...families.entries()].sort((a, b) => b[1].names.length - a[1].names.length || byName(a, b));
const multi = familyRows.filter(([, f]) => f.names.length > 1);
const hubs = [...named].sort((a, b) => b[1].refs - a[1].refs || byName(a, b)).slice(0, HUB_COUNT);

const lines: string[] = [
  '# Z80 gate-level signal map',
  '',
  `Generated by \`npm run gen:z80-map\` from \`buildZ80Cpu\` with ${ADDR_BITS} address bits. Regenerate after changing \`buildZ80CpuInner\`.`,
  '',
  '## Size',
  '',
  `- Components: ${components.length} (${[...kinds.entries()].map(([k, n]) => `${k} ${n}`).join(', ')})`,
  `- Wires: ${circuit.wires.size}`,
  `- Nets joined by label name: ${signals.size}, of which ${named.length} have hand-written names and ${signals.size - named.length} are auto-named (\`BUS0..7\`, \`_N<number>\`)`,
  `- Hand-named signals fall into ${families.size} prefix families; ${families.size - multi.length} of them hold a single signal`,
  '',
  '## Reading the tables',
  '',
  'Labels are what connect the design: a wire is drawn only between neighbouring gates, and every longer connection is a set of labels sharing one name.',
  'A family is the part of the name before the first underscore (or the name without trailing digits).',
  '"Refs" is the number of labels carrying the name. "Built between" is where the first and last label of the family appear in the order the builder creates components; a wide range means the logic of that family is spread over several places in `buildZ80CpuInner`.',
  '',
  '## Families with more than one signal',
  '',
  '| Family | Signals | Refs | Built between |',
  '|---|---:|---:|---|',
  ...multi.map(([name, f]) => `| ${name} | ${f.names.length} | ${f.refs} | ${pct(f.first)}-${pct(f.last)} |`),
  '',
  `## Most referenced signals`,
  '',
  '| Signal | Refs |',
  '|---|---:|',
  ...hubs.map(([name, s]) => `| ${name} | ${s.refs} |`),
  '',
];

writeFileSync(outPath, lines.join('\n'));
console.log('wrote', outPath, `(${multi.length} families, ${hubs.length} hubs)`);
